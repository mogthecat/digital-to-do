"""
Run on the Mac (not the Pico) to turn TTF fonts into fonts.py, the bitmap
font data main.py draws with. Needs Pillow:  python3 tools/make_fonts.py

CMU Serif is under the SIL Open Font Licence, so it is fine to embed.
Get it from https://fontlibrary.org/en/font/cmu-serif
"""

import os
from PIL import Image, ImageChops, ImageDraw, ImageFont

FONT_DIR = os.path.expanduser("~/Library/Fonts")
OUT = os.path.join(os.path.dirname(__file__), "..", "fonts.py")
FONTS = {  # name in fonts.py: (font file, pixel size)
    "HEADER": ("cmunbx.ttf", 26),  # CMU Serif Bold
    "BODY": ("cmunrm.ttf", 20),    # CMU Serif Roman
    "SMALL": ("cmunrm.ttf", 13),
}
CHARS = [chr(c) for c in range(32, 127)]  # main.py assumes this range


def make(ttf, size):
    """Return (height, widths, glyph data) with each glyph in MONO_HLSB rows."""
    font = ImageFont.truetype(os.path.join(FONT_DIR, ttf), size)
    # Line height = tallest ascender to lowest descender, from the baseline.
    boxes = {ch: font.getbbox(ch, anchor="ls") for ch in CHARS if ch != " "}
    top = min(b[1] for b in boxes.values())
    height = max(b[3] for b in boxes.values()) - top
    widths, data = bytearray(), bytearray()
    for ch in CHARS:
        w = max(1, round(font.getlength(ch)))
        img = Image.new("1", (w, height), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"  # black/white rendering keeps strokes an even 1 px
        draw.text((0, -top), ch, font=font, fill=1, anchor="ls")
        # Hinting lifts a few glyphs (e.g. 1, I, J, L) one pixel above the
        # baseline; snap any glyph that should sit on it back down.
        ink = img.getbbox()
        if ink and ink[3] == -top - 1 and boxes[ch][3] >= 0:
            img = ImageChops.offset(img, 0, 1)  # bottom row is blank, so safe to wrap
        widths.append(w)
        data += img.tobytes()  # mode "1" packs rows MSB-first = MONO_HLSB
    return height, bytes(widths), bytes(data)


with open(OUT, "w") as f:
    f.write("# Generated by tools/make_fonts.py - do not edit.\n")
    f.write("# Each font: (height, widths of chars 32-126, MONO_HLSB glyph data)\n")
    for name, (ttf, size) in FONTS.items():
        height, widths, data = make(ttf, size)
        f.write("%s = (%d, %r, bytearray(%r))  # %s %dpx\n" % (name, height, widths, data, ttf, size))
        print("%s: height %d, %d bytes" % (name, height, len(data)))
