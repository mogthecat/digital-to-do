"""
Run on the Mac (not the Pico) to turn TTF fonts into MicroPython bitmap font
modules that bitmap_font.py can draw.  Needs Pillow.

    python3 tools/make_fonts.py

CMU Serif (Computer Modern Unicode) is under the SIL Open Font Licence, so it
is fine to embed. Install it from https://fontlibrary.org/en/font/cmu-serif
or point FONTS at any other .ttf/.otf file.
"""

import os
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = os.path.expanduser("~/Library/Fonts")
OUT_DIR = os.path.join(os.path.dirname(__file__), "..")

# module name -> (font file, pixel size)
FONTS = {
    "font_header": ("cmunbx.ttf", 26),   # CMU Serif Bold
    "font_body": ("cmunrm.ttf", 20),     # CMU Serif Roman
    "font_small": ("cmunrm.ttf", 13),
}
CHARS = [chr(c) for c in range(32, 127)]  # bitmap_font.py assumes this range


def make(name, ttf, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, ttf), size)
    # Crop the line height to the ink actually used (tallest ascender to
    # lowest descender), measured from the baseline ("ls" anchor), so HEIGHT
    # can be used directly for layout.
    boxes = [font.getbbox(ch, anchor="ls") for ch in CHARS if ch != " "]
    top = min(b[1] for b in boxes)
    height = max(b[3] for b in boxes) - top
    baseline_row = -top - 1  # last pixel row of a letter sitting on the baseline
    widths, offsets, data = [], [], bytearray()
    for ch in CHARS:
        w = max(1, round(font.getlength(ch)))
        img = Image.new("1", (w, height), 0)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"  # black/white rendering keeps strokes an even 1 px
        draw.text((0, -top), ch, font=font, fill=1, anchor="ls")
        # The font's hinting lifts a few glyphs (e.g. 1, I, J, L) one pixel
        # above the baseline. Snap any glyph that should sit on the baseline
        # but stops one row short back down onto it.
        ink = img.getbbox()
        if ink and ink[3] - 1 == baseline_row - 1 and font.getbbox(ch, anchor="ls")[3] >= 0:
            snapped = Image.new("1", img.size, 0)
            snapped.paste(img, (0, 1))
            img = snapped
        offsets.append(len(data))
        widths.append(w)
        data += img.tobytes()  # mode "1" packs rows MSB-first = MONO_HLSB
    with open(os.path.join(OUT_DIR, name + ".py"), "w") as f:
        f.write("# Generated by tools/make_fonts.py from %s %dpx - do not edit.\n" % (ttf, size))
        f.write("# Characters 32-126, MONO_HLSB rows.\n")
        f.write("HEIGHT = %d\n" % height)
        f.write("WIDTHS = %r\n" % bytes(widths))
        f.write("OFFSETS = %r\n" % (tuple(offsets),))
        # bytearray, because framebuf.FrameBuffer needs writable memory
        f.write("DATA = bytearray(%r)\n" % bytes(data))
    print("%s: height %d, %d bytes" % (name, height, len(data)))


for name, (ttf, size) in FONTS.items():
    make(name, ttf, size)
